type Value = boolean | string | readonly [number, string];
function q(
	packet: string,
	id: string,
	day: number,
	values: Record<string, Value>,
	decision: Decision,
	expectedAssessments: Record<string, Tri>,
	sources: string[],
	retiredOnlySources: string[],
	category: string,
	history = false,
): SourceQuestion {
	const asOf = time(day);
	return {
		id,
		packet,
		asOf,
		question: `この状況で${packets.find((p) => p.id === packet)!.name}を許可できるか。${history ? "規程の変更経緯や従来の扱いにも触れ、今回の判断との関係を説明してください。" : "今回の判断とその根拠を説明してください。"}`,
		observations: Object.entries(values).map(([k, v]) =>
			observation(k, v, asOf),
		),
		expected: { decision, governingSources: sources, reason: category },
		expectedAssessments,
		retiredOnlySources,
		category: `${category}/${history ? "history" : "ordinary"}`,
		suite: "unseen",
	};
}
