type Value = boolean | string | readonly [number, string];
export function observation(
	key: string,
	value: Value,
	time = at(16),
	priority = 1,
	suffix = "",
): Observation {
	const typed: TypedValue =
		typeof value === "boolean"
			? { kind: "boolean", value }
			: typeof value === "string"
				? { kind: "string", value }
				: { kind: "number", value: value[0], unit: value[1] };
	return {
		observationId: `${key}${suffix}`,
		key,
		value: typed,
		observedAt: time,
		version: "v1",
		priority,
	};
}
export interface HoldoutQuestion extends Question {
	expectedAssessments: Record<string, Tri>;
	category: string;
}
function q(
	packet: string,
	id: string,
	values: Record<string, Value>,
	decision: Decision,
	sources: string[],
	results: Tri[],
	reason: string,
	category: string,
	time = at(16),
	extra: Observation[] = [],
): HoldoutQuestion {
	// Fixtures only: human-authored expected source roles and truth outcomes never enter prompts.
	const permissionSources = sources.filter(
		(s) => !["CG2", "AC3", "SB2", "FG2"].includes(s),
	);
	if (permissionSources.length !== results.length)
		throw new Error("fixture_result_count");
	return {
		packet,
		id,
		asOf: time,
		question: `この状況で${packets.find((p) => p.id === packet)!.name}を許可できるか。`,
		observations: [
			...Object.entries(values).map(([k, v]) => observation(k, v, time)),
			...extra,
		],
		expected: { decision, governingSources: sources, reason },
		expectedAssessments: Object.fromEntries(
			permissionSources.map((s, i) => [s, results[i]!]),
		),
		category,
	};
}
